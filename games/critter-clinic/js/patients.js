export const ORDER = ['puppy', 'bunny', 'bear', 'kitty', 'dino', 'elephant'];

// Who is in the waiting room: the patient whose check-up was left unfinished first, then the ones
// seen least, ties broken at random. Always three (or all of them, if there are fewer).
export function pickWaiting(seen = {}, visitId = null, rand = Math.random, ids = ORDER, n = 3) {
  const others = ids
    .filter((id) => id !== visitId)
    .map((id) => ({ id, k: (seen[id] || 0) + rand() * 0.5 }))
    .sort((a, b) => a.k - b.k)
    .map((o) => o.id);
  const out = visitId && ids.includes(visitId) ? [visitId, ...others] : others;
  return out.slice(0, n);
}
